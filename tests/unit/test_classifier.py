# ---- 断言 ----
def test_l1_samples():
    for s in L1_SAMPLES:
        assert C.classify(s) == "L1", f"应判 L1 实判 {C.classify(s)}: {s!r}"


def test_l2_samples():
    for s in L2_SAMPLES:
        assert C.classify(s) == "L2", f"应判 L2 实判 {C.classify(s)}: {s!r}"


def test_l3_samples():
    for s in L3_SAMPLES:
        assert C.classify(s) == "L3", f"应判 L3 实判 {C.classify(s)}: {s!r}"


def test_l4_recall_100():
    """重点：L4 召回率必须 100%，宁可误判不漏。"""
    miss = [s for s in L4_SAMPLES if C.classify(s) != "L4"]
    assert not miss, f"L4 漏判 {len(miss)} 条: {miss}"


def test_uncertain_default_l3():
    for s in UNCERTAIN_SAMPLES:
        assert C.classify(s) == "L3", f"不确定应默认 L3 实判 {C.classify(s)}: {s!r}"


def test_no_false_l4_on_business_numbers():
    """负样本：正常业务短数字不得误判 L4。"""
    for s in NEGATIVE_SAMPLES:
        assert C.classify(s) != "L4", f"误判 L4: {s!r}"


def test_classify_with_reason_shape():
    r = C.classify_with_reason("有问题请拨打 13800138000")
    assert r["level"] == "L4"
    assert r["insurance"] == "regex"
    assert r["reasons"]


def test_double_insurance_semantic_l4():
    """保险1：语义关键词（工资/合同）判 L4，即使无数字。"""
    assert C.classify("本月工资 8500 元") == "L4"
    assert C.classify("劳动合同已签订") == "L4"
